// PATH: tools/generate/shortcutWriter.ts

/**
 * SHORTCUT WRITER: a module-level function for every endpoint, written from the schema
 *
 * Purpose:
 *   Writes src/endpointShortcuts.ts. Every endpoint, the hand-written ones
 *   included, gets a function of its method's name that forwards to the
 *   shared client:
 *
 *     am.natal(birth)   ──► defaultClient().natal(birth)
 *
 *   A convenience surface that covered only some endpoints would read as the
 *   whole package while hiding most of it, so it covers all of them, as the
 *   Python SDK's does.
 */

import { docBlock } from "./docs.ts";
import type { SdkOperation } from "./operations.ts";

/** What the shortcut writer writes besides the functions. */
const SHORTCUT_WRITER_CONFIG = Object.freeze({
  /** The module's header, before its imports. */
  HEADER: [
    "// PATH: src/endpointShortcuts.ts",
    "",
    "/**",
    " * ENDPOINT SHORTCUTS: a module-level function for every endpoint, generated",
    " *",
    " * Purpose:",
    " *   Written by tools/generate/ from the snapshot of the API's schema,",
    " *   tools/generate/openapi.v1.json. Do not edit this file. Run",
    " *   `npm run generate` after the snapshot changes.",
    " *",
    " *   Each function forwards to the method of the same name on the shared",
    " *   client, which setApiKey() and reset() manage:",
    " *",
    ' *     import * as am from "astromansion";',
    " *     const chart = await am.natal(birth);   // defaultClient().natal(birth)",
  ],
  /** The module's imports. */
  IMPORTS: [
    'import type { AstroMansion } from "./client.ts";',
    'import { defaultClient } from "./shortcuts.ts";',
  ],
} as const);

/**
 * Write the module of the endpoint shortcuts.
 *
 * @param methods - The methods, sorted by name.
 * @returns The module's text, before formatting.
 *
 * @example
 * ```ts
 * renderEndpointShortcuts(methods).includes("export function natal(");   // true
 * ```
 */
export function renderEndpointShortcuts(
  methods: readonly SdkOperation[],
): string {
  const header = [
    ...SHORTCUT_WRITER_CONFIG.HEADER,
    " *",
    ` *   Endpoints: ${String(methods.length)}`,
    " */",
  ].join("\n");
  return [
    header,
    SHORTCUT_WRITER_CONFIG.IMPORTS.join("\n"),
    ...methods.map(shortcutText),
  ]
    .join("\n\n")
    .concat("\n");
}

/**
 * Write one shortcut with its comment.
 *
 * @param method - The method it forwards to.
 * @returns The function's text.
 */
function shortcutText(method: SdkOperation): string {
  const name = method.methodName;
  const summary = method.summary.endsWith(".")
    ? method.summary
    : `${method.summary}.`;
  // A generated method is declared on EndpointMethods, and only a hand-written one on the client.
  const owner = method.handWritten ? "AstroMansion" : "EndpointMethods";
  const target = `{@link ${owner}.${name}}`;
  return [
    docBlock(
      [
        summary,
        "",
        "@remarks",
        `Forwards to ${target} on the shared client.`,
        "",
        `@param args - The arguments ${target} takes.`,
        `@returns What ${target} returns.`,
        "@throws {@link AuthenticationError} when the shared client is built now and no key was found, and whatever the method throws.",
      ],
      "",
    ),
    `export async function ${name}(...args: Parameters<AstroMansion["${name}"]>): ReturnType<AstroMansion["${name}"]> {`,
    `  return defaultClient().${name}(...args);`,
    "}",
  ].join("\n");
}
