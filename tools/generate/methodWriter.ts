// PATH: tools/generate/methodWriter.ts

/**
 * METHOD WRITER: the module of the endpoint methods, written from the schema
 *
 * Purpose:
 *   Writes src/endpointMethods.ts, the base class every client extends.
 *   Each operation becomes one async method that takes its arguments as the
 *   Python SDK's method does, builds its body with RequestBodies, sends it
 *   through request(), and reads the answer:
 *
 *     chart         natal(fields, keywords?)                   RequestBodies.chart
 *     pair          synastry(birth, partner, keywords?)        RequestBodies.pair
 *     birth_extra   query(fields, keywords?)                   RequestBodies.body
 *     body          batch(fields, keywords?)                   RequestBodies.body
 *     get, delete   eclipses(params?), job(jobId, params?)     RequestBodies.params
 *
 *     JSON answer   readResult(answer, isNatalResponse, "natal")    the checked Result
 *     any JSON      readAnyJson(answer, "query")                    the Result, or rendered text
 *     document      saveDocument(readDocument(...), output, writer) the bytes, or the path written
 *
 *   A method the client writes by hand gets no method here.
 */

import { docBlock, docLines } from "./docs.ts";
import type { JsonAnswer, SdkOperation } from "./operations.ts";

