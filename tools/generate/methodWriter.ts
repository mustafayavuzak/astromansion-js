/** The pieces of one method's text, by its request shape. */
interface MethodParts {
  /** The method's parameters, as written in its signature. */
  readonly parameters: readonly string[];
  /** The comment lines that describe the parameters. */
  readonly parameterDocs: readonly string[];
  /** The statement that prepares the call. */
  readonly prepare: string;
  /** The members of request()'s options that carry the prepared call. */
  readonly sent: readonly string[];
}

/**
 * Write the module of the endpoint methods.
 *
 * @param methods - The methods, sorted by name.
 * @returns The module's text, before formatting.
 *
 * @example
 * ```ts
 * const text = renderEndpointMethods(methods);
 * text.includes("async natal(");   // true
 * ```
 */
export function renderEndpointMethods(
  methods: readonly SdkOperation[],
): string {
  const indent = METHOD_WRITER_CONFIG.INDENT;
  const generated = methods.filter((method) => !method.handWritten);
  const handWritten = methods
    .filter((method) => method.handWritten)
    .map((method) => method.methodName);
  const onClient = handWritten.length === 0 ? "none" : handWritten.join(", ");
  const header = [
    ...METHOD_WRITER_CONFIG.HEADER,
    " *",
    ` *   Endpoints: ${String(generated.length)}. Written on the client itself: ${onClient}.`,
    " */",
  ].join("\n");
  return [
    header,
    imports(generated),
    [
      docBlock(METHOD_WRITER_CONFIG.CLASS_COMMENT, ""),
      "export abstract class EndpointMethods {",
      docBlock(METHOD_WRITER_CONFIG.REQUEST_COMMENT, indent),
      `${indent}abstract request(method: string, path: string, options?: RequestOptions): Promise<Result | string | Uint8Array>;`,
      ...generated.map((method) => `\n${methodText(method)}`),
      "}",
    ].join("\n"),
  ]
    .join("\n\n")
    .concat("\n");
}

/**
 * Write the module's imports.
 *
 * @param methods - The methods the module writes.
 * @returns The import lines, naming exactly what the methods use.
 */
function imports(methods: readonly SdkOperation[]): string {
  const config = METHOD_WRITER_CONFIG.IMPORTS;
  const argumentTypes = new Set<string>();
  const schemaTypes = new Set<string>();
  const jsonTypes = new Set<string>();
  const generatedChecks = new Set<string>();
  const jsonTests = new Set<string>();
  const readers = new Set<string>();
  const documents = new Set<string>();
  for (const method of methods) {
    for (const name of argumentTypesOf(method)) {
      argumentTypes.add(name);
    }
    if (method.body !== undefined && signatureNamesBody(method)) {
      schemaTypes.add(method.body.typeName);
    }
    if (method.query !== undefined) {
      schemaTypes.add(method.query.typeName);
    }
    const answer = method.answer;
    if (answer.kind === "document") {
      readers.add("readDocument");
      documents.add("documentWriter").add("saveDocument");
      continue;
    }
    const reading = readingOf(method, answer);
    readers.add(reading.reader);
    if (reading.dataType !== undefined) {
      (isJsonType(answer.typeName) ? jsonTypes : schemaTypes).add(
        answer.typeName,
      );
    }
    if (reading.reader !== "readAnyJson") {
      (answer.check.generated ? generatedChecks : jsonTests).add(
        answer.check.name,
      );
    }
  }
  return [
    importLine(argumentTypes, config.ARGUMENTS, true),
    `import type { RequestOptions } from "${config.CLIENT_RECORDS}";`,
    importLine(jsonTypes, config.JSON_RECORDS, true),
    importLine(schemaTypes, config.API_SCHEMAS, true),
    `import { RequestBodies } from "${config.REQUEST_BODIES}";`,
    `import type { Result } from "${config.RESPONSE}";`,
    importLine(generatedChecks, config.ANSWER_CHECKS, false),
    importLine(readers, config.ANSWERS, false),
    importLine(documents, config.DOCUMENTS, false),
    importLine(jsonTests, config.JSON_TESTS, false),
  ]
    .filter((line) => line !== "")
    .join("\n");
}

/**
 * Write one import line.
 *
 * @param names - The names to import.
 * @param from - The module.
 * @param typesOnly - Whether the names are types, imported with `import type`.
 * @returns The line, or an empty text when there is nothing to import.
 */
function importLine(
  names: ReadonlySet<string>,
  from: string,
  typesOnly: boolean,
): string {
  if (names.size === 0) {
    return "";
  }
  const keyword = typesOnly ? "import type" : "import";
  return `${keyword} { ${[...names].sort().join(", ")} } from "${from}";`;
}

/**
 * Tell whether a method's signature names its body's type.
 *
 * @param method - The method.
 * @returns True when the body is taken whole, or its options or further fields are typed from it.
 */
function signatureNamesBody(method: SdkOperation): boolean {
  const fields = method.body?.fields ?? [];
  const pairFields: readonly string[] = METHOD_WRITER_CONFIG.PAIR_FIELDS;
  switch (method.kind) {
    case "chart":
      return fields.includes(METHOD_WRITER_CONFIG.OPTIONS_FIELD);
    case "pair":
      return (
        fields.includes(METHOD_WRITER_CONFIG.OPTIONS_FIELD) ||
        fields.some((field) => !pairFields.includes(field))
      );
    case "birth_extra":
    case "body":
      return true;
    case "get":
    case "delete":
    case "empty":
      return false;
  }
}

/**
 * Name the argument types a method's signature uses.
 *
 * @param method - The method.
 * @returns The names from the argument records.
 */
function argumentTypesOf(method: SdkOperation): readonly string[] {
  const document =
    method.answer.kind === "document" ? ["DocumentKeywords"] : [];
  switch (method.kind) {
    case "chart":
      return ["ChartFields", "ChartKeywords", ...document];
    case "pair":
      return ["BirthFields", "PairKeywords", ...document];
    case "birth_extra":
    case "body":
      return ["BodyFields", "CallKeywords", ...document];
    case "get":
    case "delete":
    case "empty":
      return method.query === undefined ? ["CallKeywords"] : ["ParamsFields"];
  }
}

/**
 * Write one method with its comment.
 *
 * @param method - The method.
 * @returns The method's text, indented for the class body.
 */
function methodText(method: SdkOperation): string {
  const indent = METHOD_WRITER_CONFIG.INDENT;
  const inner = `${indent}${indent}`;
  const parts = methodParts(method);
  const document = method.answer.kind === "document";
  const sent = [
    ...parts.sent,
    ...(document ? ["binary: true"] : []),
    `technique: ${JSON.stringify(method.operationId)}`,
    ...(method.enveloped === undefined
      ? []
      : [`enveloped: ${String(method.enveloped)}`]),
    "signal: call.signal",
  ];
  const request = `const answer = await this.request(${JSON.stringify(method.verb)}, ${pathExpression(method)}, { ${sent.join(", ")} });`;
  const body = document
    ? [
        parts.prepare,
        "const writer = documentWriter(call.output);",
        request,
        `return saveDocument(readDocument(answer, ${JSON.stringify(method.methodName)}), call.output, writer);`,
      ]
    : [parts.prepare, request, `return ${readExpression(method)};`];
  return [
    docBlock(methodComment(method, parts.parameterDocs), indent),
    `${indent}async ${method.methodName}(${[...pathParameters(method), ...parts.parameters].join(", ")}): Promise<${resultType(method)}> {`,
    ...body.map((line) => `${inner}${line}`),
    `${indent}}`,
  ].join("\n");
}

/**
 * Write the pieces of a method that its request shape decides.
 *
 * @param method - The method.
 * @returns Its parameters, their comments, the preparing statement, and what it sends.
 */
function methodParts(method: SdkOperation): MethodParts {
  const name = JSON.stringify(method.methodName);
  const document = method.answer.kind === "document";
  const documentType = document ? " & DocumentKeywords" : "";
  const typeName = method.body?.typeName;
  const options =
    typeName !== undefined &&
    method.body?.fields.includes(METHOD_WRITER_CONFIG.OPTIONS_FIELD) === true
      ? `${typeName}["options"]`
      : "never";
  const outputDoc = document
    ? " output, the path to write the document to, is allowed among them."
    : "";
  switch (method.kind) {
    case "chart":
      return {
        parameters: [
          `fields: ChartFields<${options}>${documentType}`,
          `keywords?: ChartKeywords<${options}>${documentType}`,
        ],
        parameterDocs: [
          `@param fields - The birth fields, flat: date, time, lat, lon, timezone, and houses. options and signal may stand beside them.${outputDoc}`,
          "@param keywords - The method's other arguments, when they come apart from the birth fields.",
        ],
        prepare: `const call = RequestBodies.chart(${name}, fields, keywords, ${String(document)});`,
        sent: ["json: call.json"],
      };
    case "pair": {
      const pairFields: readonly string[] = METHOD_WRITER_CONFIG.PAIR_FIELDS;
      const extraFields =
        method.body?.fields.filter((field) => !pairFields.includes(field)) ??
        [];
      const extra =
        extraFields.length === 0
          ? ""
          : `, Omit<${typeName ?? "never"}, ${pairFields.map((field) => JSON.stringify(field)).join(" | ")}>`;
      return {
        parameters: [
          "birth: BirthFields",
          "partner: BirthFields",
          `keywords?: PairKeywords<${options}${extra}>${documentType}`,
        ],
        parameterDocs: [
          "@param birth - The first person's birth fields, as natal takes them.",
          "@param partner - The second person's birth fields.",
          `@param keywords - The options, signal, and the body's further fields.${outputDoc}`,
        ],
        prepare: `const call = RequestBodies.pair(${name}, birth, partner, keywords, ${String(document)});`,
        sent: ["json: call.json"],
      };
    }
    case "birth_extra":
    case "body": {
      const optional = method.body?.required === false;
      return {
        parameters: [
          `fields${optional ? "?" : ""}: BodyFields<${typeName ?? "never"}>${documentType}`,
          `keywords?: CallKeywords${documentType}`,
        ],
        parameterDocs: [
          `@param fields - The request body, as {@link ${typeName ?? "never"}} describes it, sent as given. signal may stand beside its fields.${outputDoc}`,
          "@param keywords - signal, and output for a document, when they come apart from the body.",
        ],
        prepare: `const call = RequestBodies.body(${name}, fields${optional ? " ?? {}" : ""}, keywords, ${String(document)});`,
        sent: ["json: call.json"],
      };
    }
    case "get":
    case "delete":
    case "empty": {
      const query = method.query;
      const required = query?.required === true;
      return {
        parameters: [
          query === undefined
            ? "params?: CallKeywords"
            : `params${required ? "" : "?"}: ParamsFields<${query.typeName}>`,
        ],
        parameterDocs: [
          query === undefined
            ? "@param params - signal, which cancels the call."
            : `@param params - The query, as {@link ${query.typeName}} describes it. Parameters set to undefined or null are left out. signal may stand beside them.`,
        ],
        prepare: `const call = RequestBodies.params(${name}, params);`,
        sent: ["params: call.params"],
      };
    }
  }
}

/**
 * Write the parameters a method takes from its path.
 *
 * @param method - The method.
 * @returns One text parameter per placeholder, in the path's order.
 */
function pathParameters(method: SdkOperation): readonly string[] {
  return method.pathArguments.map((argument) => `${argument.argument}: string`);
}

/**
 * Write a method's comment.
 *
 * @param method - The method.
 * @param parameterDocs - The comments of the parameters its shape decides.
 * @returns The comment's lines.
 */
function methodComment(
  method: SdkOperation,
  parameterDocs: readonly string[],
): readonly string[] {
  const summary = method.summary.endsWith(".")
    ? method.summary
    : `${method.summary}.`;
  const description =
    method.description === undefined
      ? []
      : ["", ...docLines(method.description)];
  return [
    ...docLines(summary),
    "",
    "@remarks",
    `Sends \`${method.verb} ${method.path}\`. The Python SDK names it ${method.operationId}.`,
    ...description,
    "",
    ...method.pathArguments.map(
      (argument) =>
        `@param ${argument.argument} - ${
          argument.description === undefined
            ? `The ${argument.placeholder} segment of the path, escaped into it.`
            : docLines(argument.description).join(" ")
        }`,
    ),
    ...parameterDocs,
    `@returns ${returnsText(method)}`,
    ...(method.kind === "chart" || method.kind === "pair"
      ? [
          "@throws {@link ValidationError} when a birth field is malformed, before anything is sent, or when the API refuses the body.",
        ]
      : []),
    METHOD_WRITER_CONFIG.THROWS,
  ];
}

/** How a JSON method reads its answer: the reader it calls, and the data type its Result names. */
interface Reading {
  /** The reader, from the answers module. */
  readonly reader:
    "readResult" | "readWrapped" | "readFreeForm" | "readAnyJson";
  /** The type the Result's data has, or undefined when it is any JSON value. */
  readonly dataType: string | undefined;
}

/**
 * Decide how a JSON method reads its answer, by what the schema says about it.
 *
 * @param method - The method.
 * @param answer - Its JSON answer.
 * @returns The reader, and the data type its Result names.
 */
function readingOf(method: SdkOperation, answer: JsonAnswer): Reading {
  if (answer.anyJson) {
    return { reader: "readAnyJson", dataType: undefined };
  }
  if (method.enveloped === true) {
    return {
      reader: "readWrapped",
      dataType: answer.resultAnyJson
        ? undefined
        : `${answer.typeName}["result"]`,
    };
  }
  if (method.enveloped === undefined && isJsonType(answer.typeName)) {
    return { reader: "readFreeForm", dataType: undefined };
  }
  return { reader: "readResult", dataType: answer.typeName };
}

/**
 * Write the type a method's promise resolves to.
 *
 * @param method - The method.
 * @returns A document's bytes or the path written, a Result typed by its data, or a Result or rendered text.
 */
function resultType(method: SdkOperation): string {
  const answer = method.answer;
  if (answer.kind === "document") {
    return "Uint8Array | string";
  }
  const reading = readingOf(method, answer);
  if (reading.reader === "readAnyJson") {
    return "Result | string";
  }
  return reading.dataType === undefined
    ? "Result"
    : `Result<${reading.dataType}>`;
}

/**
 * Write what a method's promise resolves to, for its comment.
 *
 * @param method - The method.
 * @returns The sentence.
 */
function returnsText(method: SdkOperation): string {
  const answer = method.answer;
  if (answer.kind === "document") {
    return `The document's bytes, sent as ${answer.mediaTypes.join(" or ")}, or the path it was written to when output is given.`;
  }
  if (answer.anyJson) {
    return "The answer as a Result, or its text when the server rendered it as text/plain.";
  }
  const shape = isJsonType(answer.typeName)
    ? answer.typeName
    : `{@link ${answer.typeName}}`;
  return method.enveloped === true
    ? `The answer as a Result reading the result inside it, after the answer was checked against ${shape}.`
    : `The answer as a Result, checked against ${shape}.`;
}

/**
 * Write the expression of a method's path.
 *
 * @param method - The method.
 * @returns A string literal for a fixed path, or a template that escapes each argument into its placeholder.
 */
function pathExpression(method: SdkOperation): string {
  if (method.pathArguments.length === 0) {
    return JSON.stringify(method.path);
  }
  let path = method.path;
  for (const argument of method.pathArguments) {
    path = path.replace(
      `${METHOD_WRITER_CONFIG.PLACEHOLDER_OPEN}${argument.placeholder}${METHOD_WRITER_CONFIG.PLACEHOLDER_CLOSE}`,
      `\${encodeURIComponent(${argument.argument})}`,
    );
  }
  return `\`${path}\``;
}

/**
 * Write how a JSON method reads its answer.
 *
 * @param method - The method.
 * @returns The call that checks the answer and returns its Result.
 */
function readExpression(method: SdkOperation): string {
  const answer = method.answer;
  const operation = JSON.stringify(method.methodName);
  if (answer.kind === "document") {
    return `readDocument(answer, ${operation})`;
  }
  const reading = readingOf(method, answer);
  return reading.reader === "readAnyJson"
    ? `readAnyJson(answer, ${operation})`
    : `${reading.reader}(answer, ${answer.check.name}, ${operation})`;
}

/**
 * Tell whether a type is one of the client's own JSON types.
 *
 * @param typeName - The type's name.
 * @returns True for JsonObject and JsonValue.
 */
function isJsonType(typeName: string): boolean {
  return METHOD_WRITER_CONFIG.JSON_TYPES.some((type) => type === typeName);
}
