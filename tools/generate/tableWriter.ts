// PATH: tools/generate/tableWriter.ts

/**
 * TABLE WRITER: the endpoint table, written from the schema
 *
 * Purpose:
 *   Writes src/models/constants/endpoints.ts, one row per operation the API
 *   publishes, sorted by path as the Python SDK's table is. Each row names
 *   the method on both SDKs, so a test checks that the two show the same
 *   surface:
 *
 *     { name: "renderPng", operationId: "render_png", method: "POST",
 *       path: "/v1/render/png", kind: "chart", fields: ["birth", "options"],
 *       binary: true, enveloped: undefined, summary: "…" }
 */

import type { SdkOperation } from "./operations.ts";

/** What the table writer writes besides the rows. */
const TABLE_WRITER_CONFIG = Object.freeze({
  /** The module's header, before its imports. */
  HEADER: [
    "// PATH: src/models/constants/endpoints.ts",
    "",
    "/**",
    " * ENDPOINT TABLE: every operation the API publishes, generated",
    " *",
    " * Purpose:",
    " *   Written by tools/generate/ from the snapshot of the API's schema,",
    " *   tools/generate/openapi.v1.json. Do not edit this file. Run",
    " *   `npm run generate` after the snapshot changes.",
    " *",
    " *   The tests read it to check that the client and the module-level",
    " *   shortcuts cover the API, under the Python SDK's names.",
  ],
  /** The module's imports. */
  IMPORTS: 'import type { Endpoint } from "../records/endpoints.ts";',
} as const);

/**
 * Write the module of the endpoint table.
 *
 * @param methods - The methods, in any order.
 * @returns The module's text, before formatting.
 *
 * @example
 * ```ts
 * renderEndpointTable(methods).includes('operationId: "render_png"');   // true
 * ```
 */
export function renderEndpointTable(methods: readonly SdkOperation[]): string {
  const rows = [...methods].sort((left, right) =>
    left.path < right.path ? -1 : left.path > right.path ? 1 : 0,
  );
  const header = [
    ...TABLE_WRITER_CONFIG.HEADER,
    " *",
    ` *   Endpoints: ${String(rows.length)}`,
    " */",
  ].join("\n");
  return [
    header,
    TABLE_WRITER_CONFIG.IMPORTS,
    [
      "/**",
      " * Every operation the API publishes, sorted by path.",
      " *",
      " * @internal",
      " */",
      `const ALL = Object.freeze([${rows.map(rowText).join(",")}] as const satisfies readonly Endpoint[]);`,
    ].join("\n"),
    [
      "/**",
      " * The operations the API publishes, in order and by method name.",
      " *",
      " * @internal",
      " */",
      "export const ENDPOINTS = Object.freeze({",
      "  /** Every operation, sorted by path. */",
      "  ALL,",
      "  /** Every operation, by its method's name. */",
      "  BY_NAME: Object.freeze(Object.fromEntries(ALL.map((endpoint) => [endpoint.name, endpoint]))),",
      "});",
    ].join("\n"),
  ]
    .join("\n\n")
    .concat("\n");
}

/**
 * Write one row of the table.
 *
 * @param method - The method the row describes.
 * @returns The row as an object literal.
 */
function rowText(method: SdkOperation): string {
  const members = [
    `name: ${JSON.stringify(method.methodName)}`,
    `operationId: ${JSON.stringify(method.operationId)}`,
    `method: ${JSON.stringify(method.verb)}`,
    `path: ${JSON.stringify(method.path)}`,
    `kind: ${JSON.stringify(method.kind)}`,
    `fields: [${method.fields.map((field) => JSON.stringify(field)).join(", ")}]`,
    `binary: ${String(method.answer.kind === "document")}`,
    `enveloped: ${method.enveloped === undefined ? "undefined" : String(method.enveloped)}`,
    `summary: ${JSON.stringify(method.tableSummary)}`,
  ];
  return `{ ${members.join(", ")} }`;
}
