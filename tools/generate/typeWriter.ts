// PATH: tools/generate/typeWriter.ts

/**
 * TYPE WRITER: the module of the API's shapes, written from the schema
 *
 * Purpose:
 *   Writes src/models/schemas/api.ts, the types a caller passes to the
 *   generated methods and receives from them:
 *
 *     component, a closed set   export type MoonPhase = "New Moon" | "Full Moon" | …
 *     component, a shape        export type BirthPayload = Readonly<{ date: BirthDate; … }>
 *     component, any JSON       not written, JsonValue stands for it
 *     a method's query          export type SearchPlacesQuery = Readonly<{ q: string; … }>
 *     a method's own answer     a type named for the method, such as ChartAnswer
 *
 *   An object is a Readonly type literal, the form of a JSON value that
 *   TypeScript lets stand wherever a JsonValue may, so a request body goes
 *   out as JSON without a cast.
 *
 * Contexts:
 *   A component an answer reaches is written for answers. A closed set
 *   inside it is an OpenSet, the values this release knows or one a later
 *   API release added. A member that names null may also be missing, since
 *   some answers leave null members out. Every other component is written
 *   for requests, exactly as the schema says.
 */

import { docBlock, docLines, limitLines, paragraphs } from "./docs.ts";
import {
  GeneratorError,
  type SchemaNode,
  type SchemaProperty,
} from "./openApi.ts";
import type { SdkOperation } from "./operations.ts";
import { namesNull, type ShapeCatalog } from "./shapes.ts";

/** What the type writer writes besides the types. */
const TYPE_WRITER_CONFIG = Object.freeze({
  /** The module's header, before its imports. */
  HEADER: [
    "// PATH: src/models/schemas/api.ts",
    "",
    "/**",
    " * API SCHEMAS: the shapes of what the API takes and answers, generated",
    " *",
    " * Purpose:",
    " *   Written by tools/generate/ from the snapshot of the API's schema,",
    " *   tools/generate/openapi.v1.json. Do not edit this file. Run",
    " *   `npm run generate` after the snapshot changes.",
    " *",
    " * Shapes:",
    " *   Each component schema of the API is one type here, and so is the query",
    " *   of each method that takes one. An object is a Readonly type literal,",
    " *   the form of a JSON value TypeScript lets stand wherever a JsonValue",
    " *   may.",
    " *",
    " * Answers:",
    " *   A shape an answer reaches is read tolerantly. A member it does not name",
    " *   is ignored. A closed set inside it is an OpenSet, the values this",
    " *   release knows or one a later API release added. A member that may be",
    " *   null may also be missing, since some answers leave null members out.",
    " */",
  ].join("\n"),
  /** Where the module imports the client's JSON types from. */
  JSON_RECORDS: "../records/json.ts",
  /** The names the package already exports, which no generated type may take. */
  RESERVED_NAMES: Object.freeze([
    "AstroMansion",
    "EndpointMethods",
    "AstroMansionError",
    "AstroMansionConnectionError",
    "AstroMansionErrorInit",
    "AuthenticationError",
    "ConflictError",
    "NotFoundError",
    "PermissionDeniedError",
    "QuotaExceededError",
    "RateLimitError",
    "ServerError",
    "ValidationError",
    "ErrorPolicy",
    "Result",
    "ResultConstructor",
    "ResultFields",
    "ResultMembers",
    "BirthFields",
    "BodiesFields",
    "BodyFields",
    "CallKeywords",
    "CatalogProgress",
    "ChartFields",
    "ChartKeywords",
    "DocumentKeywords",
    "PairKeywords",
    "ParamsFields",
    "SharecardKeywords",
    "ClientOptions",
    "FetchFunction",
    "QueryValue",
    "RequestOptions",
    "JsonArray",
    "JsonObject",
    "JsonPrimitive",
    "JsonValue",
    "OpenSet",
  ] as const),
  /** The indentation of one level. */
  INDENT: "  ",
  /**
   * A member name that needs no quotes as a key: a letter, `_`, or `$`,
   * then letters, digits, `_`, or `$`. Accepts `birth`, `created_at`, and
   * `$ref`. Refuses `2nd`, `wheel-size`, and the empty name.
   */
  IDENTIFIER: /^[A-Za-z_$][A-Za-z0-9_$]*$/,
} as const);

/** The client's JSON types a generated type may use. */
type JsonType = "JsonObject" | "JsonValue" | "OpenSet";

/** Whom a shape is written for. */
type Context = "request" | "answer";

/** One declaration of the module, kept with its name for the sorting. */
interface Declaration {
  /** The declared type's name. */
  readonly name: string;
  /** The declaration's text, its comment included. */
  readonly text: string;
}

/**
 * Write the module of the API's shapes.
 *
 * @param methods - The methods, whose queries and own answers get types.
 * @param catalog - The document's components.
 * @param writtenComponents - The components a method sends or receives, the only ones written.
 * @param answerComponents - The components an answer reaches, written for answers.
 * @returns The module's text, before formatting.
 * @throws {@link GeneratorError} when two types would share a name, a type would take a name the package exports, or a schema holds a construct the writer cannot write.
 *
 * @example
 * ```ts
 * const text = renderSchemaTypes(methods, catalog, methodReach(methods, catalog), answerReach(methods, catalog));
 * text.includes("export type BirthPayload = Readonly<{");   // true
 * ```
 */
export function renderSchemaTypes(
  methods: readonly SdkOperation[],
  catalog: ShapeCatalog,
  writtenComponents: ReadonlySet<string>,
  answerComponents: ReadonlySet<string>,
): string {
  return new TypeWriter(catalog, answerComponents).render(
    methods,
    writtenComponents,
  );
}

/**
 * Writes the types of one run.
 *
 * @remarks
 * Holds the JSON types the written module uses, so its import names
 * exactly those. One writer serves one render. The class is closed to
 * extension.
 */
class TypeWriter {
  readonly #catalog: ShapeCatalog;
  readonly #answerComponents: ReadonlySet<string>;
  readonly #jsonTypes = new Set<JsonType>();

  /**
   * Keep what the run reads.
   *
   * @param catalog - The document's components.
   * @param answerComponents - The components an answer reaches.
   */
  constructor(catalog: ShapeCatalog, answerComponents: ReadonlySet<string>) {
    this.#catalog = catalog;
    this.#answerComponents = answerComponents;
  }

  /**
   * Write the module.
   *
   * @param methods - The methods, whose queries and own answers get types.
   * @param writtenComponents - The components to write.
   * @returns The module's text.
   * @throws {@link GeneratorError} when two types would share a name or a schema cannot be written.
   */
  render(
    methods: readonly SdkOperation[],
    writtenComponents: ReadonlySet<string>,
  ): string {
    const declarations = [
      ...[...writtenComponents].flatMap((name) => this.#component(name)),
      ...methods.flatMap((method) => this.#query(method)),
      ...methods.flatMap((method) => this.#ownAnswer(method)),
    ].sort((left, right) => left.name.localeCompare(right.name));
    checkNames(declarations);
    const imports =
      this.#jsonTypes.size === 0
        ? []
        : [
            `import type { ${[...this.#jsonTypes].sort().join(", ")} } from "${TYPE_WRITER_CONFIG.JSON_RECORDS}";`,
          ];
    return [
      TYPE_WRITER_CONFIG.HEADER,
      ...imports,
      ...declarations.map((declaration) => declaration.text),
    ]
      .join("\n\n")
      .concat("\n");
  }

  /**
   * Declare one component.
   *
   * @param name - The component's name.
   * @returns The declaration, or none for a component of any JSON, which JsonValue stands for.
   */
  #component(name: string): readonly Declaration[] {
    const kind = this.#catalog.kindOf(name);
    const schema = this.#catalog.component(name);
    switch (kind) {
      case "anyJson":
        return [];
      case "closedSet":
        return [
          {
            name,
            text: declared(
              name,
              paragraphs([
                docLines(schema.description ?? `The values ${name} takes.`),
                limitLines(schema.limits),
              ]),
              closedUnion(schema),
            ),
          },
        ];
      case "shape":
        return [
          {
            name,
            text: declared(
              name,
              paragraphs([
                docLines(
                  schema.description ??
                    `The ${name} value, as the API's schema defines it.`,
                ),
                limitLines(schema.limits),
              ]),
              this.#expression(schema, this.#contextOf(name), ""),
            ),
          },
        ];
    }
  }

  /**
   * Declare a method's query type.
   *
   * @param method - The method.
   * @returns The declaration, or none when the method takes no query.
   */
  #query(method: SdkOperation): readonly Declaration[] {
    const query = method.query;
    if (query === undefined) {
      return [];
    }
    const members = query.parameters.map((parameter) =>
      this.#member(
        parameter.name,
        parameter.required,
        parameter.schema,
        parameter.description,
        "request",
        TYPE_WRITER_CONFIG.INDENT,
      ),
    );
    return [
      {
        name: query.typeName,
        text: declared(
          query.typeName,
          [
            `The query of ${method.methodName}, sent with ${method.verb} ${method.path}.`,
          ],
          `Readonly<{\n${members.join("\n")}\n}>`,
        ),
      },
    ];
  }

  /**
   * Declare the type of an answer written for one method alone.
   *
   * @param method - The method.
   * @returns The declaration, or none when a component or a JSON type names the answer.
   */
  #ownAnswer(method: SdkOperation): readonly Declaration[] {
    const answer = method.answer;
    if (answer.kind !== "json" || answer.ownSchema === undefined) {
      return [];
    }
    return [
      {
        name: answer.typeName,
        text: declared(
          answer.typeName,
          paragraphs([
            [
              `What ${method.methodName} answers with, ${method.verb} ${method.path}.`,
            ],
            answer.ownSchema.description === undefined
              ? []
              : docLines(answer.ownSchema.description),
          ]),
          this.#expression(answer.ownSchema, "answer", ""),
        ),
      },
    ];
  }

  /**
   * Write the type a schema describes.
   *
   * @param schema - The schema.
   * @param context - Whom the shape is written for.
   * @param indent - The indentation of the line the type starts on.
   * @returns The type's text.
   * @throws {@link GeneratorError} when the schema holds a construct the writer cannot write.
   */
  #expression(schema: SchemaNode, context: Context, indent: string): string {
    if (schema.ref !== undefined) {
      return this.#reference(schema.ref, context);
    }
    if (schema.anyOf !== undefined) {
      const members = [
        ...new Set(
          schema.anyOf.map((member) =>
            this.#expression(member, context, indent),
          ),
        ),
      ];
      const anyJson: JsonType = "JsonValue";
      return members.includes(anyJson)
        ? this.#json(anyJson)
        : members.join(" | ");
    }
    if (schema.constValue !== undefined) {
      return JSON.stringify(schema.constValue.value);
    }
    if (schema.enumValues !== undefined) {
      const union = closedUnion(schema);
      return context === "answer" && isTextSet(schema)
        ? `${this.#json("OpenSet")}<${union}>`
        : union;
    }
    switch (schema.type) {
      case "string":
        return "string";
      case "number":
      case "integer":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        if (schema.prefixItems !== undefined) {
          return `readonly [${schema.prefixItems
            .map((item) => this.#expression(item, context, indent))
            .join(", ")}]`;
        }
        return `readonly ${grouped(
          schema.items === undefined
            ? this.#json("JsonValue")
            : this.#expression(schema.items, context, indent),
        )}[]`;
      case "object":
        return this.#object(schema, context, indent);
      case undefined:
        return schema.properties === undefined
          ? this.#json("JsonValue")
          : this.#object(schema, context, indent);
    }
  }

  /**
   * Write a reference to a component.
   *
   * @param name - The component's name.
   * @param context - Whom the shape that refers to it is written for.
   * @returns JsonValue for any JSON, an OpenSet of the set in an answer, or the component's name.
   */
  #reference(name: string, context: Context): string {
    switch (this.#catalog.kindOf(name)) {
      case "anyJson":
        return this.#json("JsonValue");
      case "closedSet":
        return context === "answer" && isTextSet(this.#catalog.component(name))
          ? `${this.#json("OpenSet")}<${name}>`
          : name;
      case "shape":
        return name;
    }
  }

  /**
   * Write an object type.
   *
   * @param schema - The object's schema.
   * @param context - Whom the shape is written for.
   * @param indent - The indentation of the line the type starts on.
   * @returns A Readonly type literal of its members, a Readonly record of its values, or JsonObject.
   * @throws {@link GeneratorError} when the schema lists members and a schema for its other members together.
   */
  #object(schema: SchemaNode, context: Context, indent: string): string {
    const others = schema.additionalProperties;
    if (schema.properties === undefined) {
      if (typeof others === "object") {
        return `Readonly<Record<string, ${this.#expression(others, context, indent)}>>`;
      }
      return others === false
        ? "Readonly<Record<string, never>>"
        : this.#json("JsonObject");
    }
    if (typeof others === "object") {
      throw new GeneratorError(
        `${schema.at} lists members and a schema for its other members, which the generator cannot write`,
      );
    }
    const inner = `${indent}${TYPE_WRITER_CONFIG.INDENT}`;
    const members = schema.properties.map((property) =>
      this.#propertyMember(property, context, inner),
    );
    return `Readonly<{\n${members.join("\n")}\n${indent}}>`;
  }

  /**
   * Write one member of an object schema.
   *
   * @param property - The member.
   * @param context - Whom the shape is written for.
   * @param indent - The member's indentation.
   * @returns The member's line, after its comment when it has one.
   */
  #propertyMember(
    property: SchemaProperty,
    context: Context,
    indent: string,
  ): string {
    return this.#member(
      property.name,
      property.required,
      property.schema,
      property.schema.description,
      context,
      indent,
    );
  }

  /**
   * Write one member of an object type.
   *
   * @param name - The member's name on the wire.
   * @param required - Whether the schema requires it.
   * @param schema - The member's schema.
   * @param description - The member's prose, or undefined without any.
   * @param context - Whom the shape is written for.
   * @param indent - The member's indentation.
   * @returns The member's line, after its comment when it has one.
   */
  #member(
    name: string,
    required: boolean,
    schema: SchemaNode,
    description: string | undefined,
    context: Context,
    indent: string,
  ): string {
    const present =
      required && !(context === "answer" && namesNull(schema, this.#catalog));
    const lines = paragraphs([
      description === undefined ? [] : docLines(description),
      limitLines(schema.limits),
    ]);
    const line = `${indent}${memberKey(name)}${present ? "" : "?"}: ${this.#expression(schema, context, indent)};`;
    return lines.length === 0 ? line : `${docBlock(lines, indent)}\n${line}`;
  }

  /**
   * Tell whom a component is written for.
   *
   * @param name - The component's name.
   * @returns Answer when an answer reaches it, request otherwise.
   */
  #contextOf(name: string): Context {
    return this.#answerComponents.has(name) ? "answer" : "request";
  }

  /**
   * Use one of the client's JSON types, which the module then imports.
   *
   * @param type - The JSON type.
   * @returns Its name.
   */
  #json(type: JsonType): JsonType {
    this.#jsonTypes.add(type);
    return type;
  }
}

/**
 * Write a type declaration with its comment.
 *
 * @param name - The type's name.
 * @param lines - The comment's lines.
 * @param type - The type's text.
 * @returns The declaration.
 */
function declared(
  name: string,
  lines: readonly string[],
  type: string,
): string {
  return `${docBlock(lines, "")}\nexport type ${name} = ${type};`;
}

/**
 * Write a closed set as the union of its literals.
 *
 * @param schema - The set's schema.
 * @returns The literals, joined as a union.
 * @throws {@link GeneratorError} when the set is empty.
 */
function closedUnion(schema: SchemaNode): string {
  const values = schema.enumValues ?? [];
  if (values.length === 0) {
    throw new GeneratorError(`${schema.at} is a closed set without values`);
  }
  return values.map((value) => JSON.stringify(value)).join(" | ");
}

/**
 * Tell whether a closed set holds texts only.
 *
 * @param schema - The set's schema.
 * @returns True when every value is a text, so a later release may add one.
 */
function isTextSet(schema: SchemaNode): boolean {
  return (schema.enumValues ?? []).every((value) => typeof value === "string");
}

/**
 * Wrap a type in parentheses where it stands as the items of an array type.
 *
 * @remarks
 * A union would otherwise spread over the brackets, and a list or a tuple
 * would read `readonly readonly …`, which TypeScript refuses.
 *
 * @param type - The type's text.
 * @returns The text, in parentheses when it holds a union or is itself a list or a tuple.
 */
function grouped(type: string): string {
  return type.includes(" | ") || type.startsWith("readonly ")
    ? `(${type})`
    : type;
}

/**
 * Write a member's name as a key.
 *
 * @param name - The name on the wire.
 * @returns The name as it is when it is an identifier, quoted otherwise.
 */
function memberKey(name: string): string {
  return TYPE_WRITER_CONFIG.IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

/**
 * Refuse two types of one name, and a name the package already exports.
 *
 * @param declarations - The module's declarations.
 * @throws {@link GeneratorError} when a name repeats or is reserved.
 */
function checkNames(declarations: readonly Declaration[]): void {
  const taken = new Set<string>();
  for (const { name } of declarations) {
    if (taken.has(name)) {
      throw new GeneratorError(`two types would both be named ${name}`);
    }
    if (
      TYPE_WRITER_CONFIG.RESERVED_NAMES.some((reserved) => reserved === name)
    ) {
      throw new GeneratorError(
        `a type would be named ${name}, which the package already exports`,
      );
    }
    taken.add(name);
  }
}
