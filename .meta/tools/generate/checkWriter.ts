// PATH: .meta/tools/generate/checkWriter.ts

/**
 * CHECK WRITER: the module of the answer checks, written from the schema
 *
 * Purpose:
 *   Writes src/responses/answerChecks.ts, one check for each shape an
 *   answer reaches and for each answer type written for one method alone.
 *   A check reads a value member by member, exactly as tolerantly as the
 *   type it proves:
 *
 *     object        isJsonObject(value) && one test per member it names
 *     member        required: its test, optional: missing or its test
 *     closed set    a text, since a later API release may add a value
 *     union         one of its members' tests
 *     list          isJsonArrayOf(value, its items' test)
 *     record        isJsonRecordOf(value, its values' test)
 *     any JSON      present when required, and no test otherwise
 *
 *   A member the shape does not name is never read, so an answer that
 *   gained a member still passes.
 */

import { docBlock } from "./docs.ts";
import { GeneratorError, type SchemaNode } from "./openApi.ts";
import type { SdkOperation } from "./operations.ts";
import { namesNull, type ShapeCatalog } from "./shapes.ts";

/** What the check writer writes besides the checks. */
const CHECK_WRITER_CONFIG = Object.freeze({
  /** The module's header, before its imports. */
  HEADER: [
    "// PATH: src/responses/answerChecks.ts",
    "",
    "/**",
    " * ANSWER CHECKS: whether an answer has the shape the API publishes, generated",
    " *",
    " * Purpose:",
    " *   Written by .meta/tools/generate/ from the snapshot of the API's schema,",
    " *   .meta/openapi/openapi.v1.json. Do not edit this file. Run",
    " *   `npm run generate` after the snapshot changes.",
    " *",
    " *   Each generated method runs its answer's check before it returns the",
    " *   answer, so the type a caller receives is one the value really has.",
    " *",
    " * Tolerance:",
    " *   A check reads only the members its shape names, so an answer that",
    " *   gained a member still passes. A closed set accepts any text, since a",
    " *   later API release may add a value. A member that may be null may also",
    " *   be missing, since some answers leave null members out.",
    " */",
  ].join("\n"),
  /** Where the module imports the client's JSON type, the shapes, and the JSON tests from. */
  JSON_RECORDS: "../models/records/json.ts",
  API_SCHEMAS: "../models/schemas/api.ts",
  JSON_TESTS: "./json.ts",
  /** The prefix of a check's name, before its shape's name. */
  CHECK_PREFIX: "is",
  /** The name of a check's argument, and the prefixes of the names a nested test gives its own. */
  VALUE: "value",
  ITEM: "item",
  MEMBER: "member",
} as const);

/** The client's JSON tests a check may call. */
type JsonTest = "isJsonArrayOf" | "isJsonObject" | "isJsonRecordOf";

/**
 * Write the module of the answer checks.
 *
 * @param methods - The methods, whose own answer types get checks.
 * @param catalog - The document's components.
 * @param answerComponents - The components an answer reaches, each shape of which gets a check.
 * @returns The module's text, before formatting.
 * @throws {@link GeneratorError} when a shape holds a construct the writer cannot check.
 *
 * @example
 * ```ts
 * const text = renderAnswerChecks(methods, catalog, answerReach(methods, catalog));
 * text.includes("export function isNatalResponse(");   // true
 * ```
 */
export function renderAnswerChecks(
  methods: readonly SdkOperation[],
  catalog: ShapeCatalog,
  answerComponents: ReadonlySet<string>,
): string {
  return new CheckWriter(catalog).render(methods, answerComponents);
}

/**
 * Writes the checks of one run.
 *
 * @remarks
 * Holds the shapes and the JSON tests the written module uses, so its
 * imports name exactly those. One writer serves one render. The class is
 * closed to extension.
 */
class CheckWriter {
  readonly #catalog: ShapeCatalog;
  readonly #shapes = new Set<string>();
  readonly #tests = new Set<JsonTest>();

  /**
   * Keep the document's components.
   *
   * @param catalog - The document's components.
   */
  constructor(catalog: ShapeCatalog) {
    this.#catalog = catalog;
  }

  /**
   * Write the module.
   *
   * @param methods - The methods, whose own answer types get checks.
   * @param answerComponents - The components an answer reaches.
   * @returns The module's text.
   */
  render(
    methods: readonly SdkOperation[],
    answerComponents: ReadonlySet<string>,
  ): string {
    const checked = [
      ...[...answerComponents]
        .filter((name) => this.#catalog.kindOf(name) === "shape")
        .map((name) => ({ name, schema: this.#catalog.component(name) })),
      ...methods.flatMap((method) =>
        method.answer.kind === "json" && method.answer.ownSchema !== undefined
          ? [{ name: method.answer.typeName, schema: method.answer.ownSchema }]
          : [],
      ),
    ].sort((left, right) => left.name.localeCompare(right.name));
    const checks = checked.map(({ name, schema }) => this.#check(name, schema));
    return [
      CHECK_WRITER_CONFIG.HEADER,
      this.#imports(checked.map(({ name }) => name)),
      ...checks,
    ]
      .join("\n\n")
      .concat("\n");
  }

  /**
   * Write the module's imports.
   *
   * @param checkedNames - The names of the shapes the module checks.
   * @returns The import lines.
   */
  #imports(checkedNames: readonly string[]): string {
    const shapes = [...new Set([...checkedNames, ...this.#shapes])].sort();
    const tests = [...this.#tests].sort();
    return [
      `import type { JsonValue } from "${CHECK_WRITER_CONFIG.JSON_RECORDS}";`,
      ...(shapes.length === 0
        ? []
        : [
            `import type { ${shapes.join(", ")} } from "${CHECK_WRITER_CONFIG.API_SCHEMAS}";`,
          ]),
      ...(tests.length === 0
        ? []
        : [
            `import { ${tests.join(", ")} } from "${CHECK_WRITER_CONFIG.JSON_TESTS}";`,
          ]),
    ].join("\n");
  }

  /**
   * Write the check of one shape.
   *
   * @param name - The shape's name.
   * @param schema - The shape's schema.
   * @returns The check function with its comment.
   */
  #check(name: string, schema: SchemaNode): string {
    const value = CHECK_WRITER_CONFIG.VALUE;
    const body = this.#isObjectWithMembers(schema)
      ? this.#objectBody(schema, value)
      : (this.#test(schema, value, 0) ?? `${value} !== undefined`);
    return [
      docBlock(
        [
          `Check that a value has the {@link ${name}} shape.`,
          "",
          "@internal",
          `@param ${value} - A value from an answer.`,
          `@returns True when the value has every member ${name} requires, each of its published type.`,
        ],
        "",
      ),
      `export function ${CHECK_WRITER_CONFIG.CHECK_PREFIX}${name}(${value}: JsonValue | undefined): ${value} is ${name} {`,
      `  return ${body};`,
      "}",
    ].join("\n");
  }

  /**
   * Write the test of an object that names its members, member by member.
   *
   * @param schema - The object's schema.
   * @param value - The expression that reads the object.
   * @returns The test.
   */
  #objectBody(schema: SchemaNode, value: string): string {
    this.#tests.add("isJsonObject");
    const tests = [`isJsonObject(${value})`];
    for (const property of schema.properties ?? []) {
      const member = `${value}[${JSON.stringify(property.name)}]`;
      const test = this.#test(property.schema, member, 0);
      const mayBeMissing =
        !property.required || namesNull(property.schema, this.#catalog);
      if (!mayBeMissing) {
        tests.push(test ?? `${member} !== undefined`);
      } else if (test !== undefined) {
        tests.push(`(${member} === undefined || ${test})`);
      }
    }
    return tests.join(" && ");
  }

  /**
   * Write the test of a value against a schema.
   *
   * @param schema - The schema.
   * @param value - The expression that reads the value.
   * @param depth - How many nested tests stand around this one, which keeps their argument names apart.
   * @returns The test, or undefined when any present value passes.
   * @throws {@link GeneratorError} when the schema is an object that names members without being a component.
   */
  #test(schema: SchemaNode, value: string, depth: number): string | undefined {
    if (schema.ref !== undefined) {
      return this.#referenceTest(schema.ref, value);
    }
    if (schema.anyOf !== undefined) {
      const tests = schema.anyOf.map((member) =>
        this.#test(member, value, depth),
      );
      return tests.some((test) => test === undefined)
        ? undefined
        : `(${tests.join(" || ")})`;
    }
    if (schema.constValue !== undefined) {
      return `${value} === ${JSON.stringify(schema.constValue.value)}`;
    }
    if (schema.enumValues !== undefined) {
      return closedSetTest(schema, value);
    }
    switch (schema.type) {
      case "string":
        return `typeof ${value} === "string"`;
      case "number":
        return `typeof ${value} === "number"`;
      case "integer":
        return `Number.isInteger(${value})`;
      case "boolean":
        return `typeof ${value} === "boolean"`;
      case "null":
        return `${value} === null`;
      case "array":
        return this.#listTest(schema, value, depth);
      case "object":
        return this.#recordTest(schema, value, depth);
      case undefined:
        return schema.properties === undefined
          ? undefined
          : this.#recordTest(schema, value, depth);
    }
  }

  /**
   * Write the test of a value against a component.
   *
   * @param name - The component's name.
   * @param value - The expression that reads the value.
   * @returns No test for any JSON, the closed set's test, or the call of the shape's check.
   */
  #referenceTest(name: string, value: string): string | undefined {
    switch (this.#catalog.kindOf(name)) {
      case "anyJson":
        return undefined;
      case "closedSet":
        return closedSetTest(this.#catalog.component(name), value);
      case "shape":
        this.#shapes.add(name);
        return `${CHECK_WRITER_CONFIG.CHECK_PREFIX}${name}(${value})`;
    }
  }

  /**
   * Write the test of a list.
   *
   * @param schema - The list's schema.
   * @param value - The expression that reads the list.
   * @param depth - How many nested tests stand around this one.
   * @returns The test of a list whose every item passes the items' test.
   */
  #listTest(schema: SchemaNode, value: string, depth: number): string {
    this.#tests.add("isJsonArrayOf");
    const item = `${CHECK_WRITER_CONFIG.ITEM}${String(depth)}`;
    const test =
      schema.items === undefined
        ? undefined
        : this.#test(schema.items, item, depth + 1);
    return test === undefined
      ? `isJsonArrayOf(${value})`
      : `isJsonArrayOf(${value}, (${item}) => ${test})`;
  }

  /**
   * Write the test of an object that names no members.
   *
   * @param schema - The object's schema.
   * @param value - The expression that reads the object.
   * @param depth - How many nested tests stand around this one.
   * @returns The test of an object whose every value passes the values' test, or of any object.
   * @throws {@link GeneratorError} when the object names members, which only a component may.
   */
  #recordTest(schema: SchemaNode, value: string, depth: number): string {
    if (schema.properties !== undefined) {
      throw new GeneratorError(
        `${schema.at} is an object that names its members inside an answer, which only a component may`,
      );
    }
    const others = schema.additionalProperties;
    const member = `${CHECK_WRITER_CONFIG.MEMBER}${String(depth)}`;
    const test =
      typeof others === "object"
        ? this.#test(others, member, depth + 1)
        : undefined;
    if (test === undefined) {
      this.#tests.add("isJsonObject");
      return `isJsonObject(${value})`;
    }
    this.#tests.add("isJsonRecordOf");
    return `isJsonRecordOf(${value}, (${member}) => ${test})`;
  }

  /**
   * Tell whether a shape is an object that names its members.
   *
   * @param schema - The shape's schema.
   * @returns True for an object type, or a schema without a type, that lists members.
   */
  #isObjectWithMembers(schema: SchemaNode): boolean {
    return (
      schema.ref === undefined &&
      schema.properties !== undefined &&
      (schema.type === "object" || schema.type === undefined)
    );
  }
}

/**
 * Write the test of a closed set in an answer.
 *
 * @param schema - The set's schema.
 * @param value - The expression that reads the value.
 * @returns A text test for a set of texts, which a later release may extend, and one comparison per value otherwise.
 */
function closedSetTest(schema: SchemaNode, value: string): string {
  const values = schema.enumValues ?? [];
  if (values.every((member) => typeof member === "string")) {
    return `typeof ${value} === "string"`;
  }
  return `(${values.map((member) => `${value} === ${JSON.stringify(member)}`).join(" || ")})`;
}
