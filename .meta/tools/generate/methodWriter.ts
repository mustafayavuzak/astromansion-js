// PATH: .meta/tools/generate/methodWriter.ts

/**
 * METHOD WRITER: the module of the endpoint methods, written from the schema
 *
 * Purpose:
 *   Writes src/endpointMethods.ts, the base class every client extends.
 *   Each operation becomes one async method, which sends its arguments
 *   through request() and reads the answer:
 *
 *     JSON answer      return readJson(answer, isNatalResponse, "natal");
 *     wrapper answer   return readJson(answer, isTechniqueEnvelope, "transits").result;
 *     document         return readDocument(answer, "renderPng");
 *
 *   A path placeholder becomes an argument escaped into the path, a query
 *   becomes one argument of the method's query type, and a body one
 *   argument of its component's type.
 */

import { docBlock, docLines } from "./docs.ts";
import type { SdkOperation } from "./operations.ts";

/** What the method writer writes besides the methods. */
const METHOD_WRITER_CONFIG = Object.freeze({
  /** The module's header and the class's comment, before and after the imports. */
  HEADER: [
    "// PATH: src/endpointMethods.ts",
    "",
    "/**",
    " * ENDPOINT METHODS: one method per operation the API publishes, generated",
    " *",
    " * Purpose:",
    " *   Written by .meta/tools/generate/ from the snapshot of the API's schema,",
    " *   .meta/openapi/openapi.v1.json. Do not edit this file. Run",
    " *   `npm run generate` after the snapshot changes.",
    " *",
    " *   Each method sends its arguments through request() and checks the",
    " *   answer against the shape the API publishes before it returns it:",
    " *",
    " *     JSON answer      the answer, its type checked by its answer check",
    " *     wrapper answer   the result inside {technique, result}, after the wrapper is checked",
    " *     document         the document's bytes, such as a PNG image or a PDF",
    " */",
  ].join("\n"),
  CLASS_COMMENT: [
    "The methods every client has, one per operation the API publishes.",
    "",
    "@remarks",
    "Build an {@link AstroMansion}, which extends this class with request()",
    "and the key, the API root, and the retries it sends with. Each method",
    "checks its answer against the shape the API publishes before returning",
    "it. The class is open for extension by AstroMansion alone.",
    "",
    "@example",
    "```ts",
    "const client = new AstroMansion();   // reads ASTROMANSION_API_KEY",
    'const birth = { date: "2000-01-01", time: "12:00", lat: 51.4779, lon: 0 };',
    "const chart = await client.natal({ birth });             // NatalResponse",
    "const image = await client.renderPng({ birth });         // the PNG's bytes",
    "const eclipses = await client.eclipses({ year: 2027 });  // EclipsesResponse",
    "```",
    "",
    "@example",
    "An answer outside its published shape still reaches the caller:",
    "```ts",
    "try {",
    "  await client.natal({ birth });",
    "} catch (error) {",
    '  if (error instanceof AstroMansionError && error.errorCode === "unexpected_answer") {',
    "    console.error(error.details);   // the answer as it arrived",
    "  }",
    "}",
    "```",
  ],
  REQUEST_COMMENT: [
    "Send one request and read its answer, the call every method makes.",
    "",
    "@remarks",
    "{@link AstroMansion.request} implements it and documents what it throws.",
    "",
    "@param method - The HTTP method.",
    "@param path - A path beginning with /v1/.",
    "@param options - The body, the query, and how the answer is read.",
    "@returns The JSON value, text for a text/plain answer, or bytes for a document.",
  ],
  /** Where the module imports from. */
  IMPORTS: Object.freeze({
    HTTP_METHOD: "./models/enums/http.ts",
    CLIENT_RECORDS: "./models/records/client.ts",
    JSON_RECORDS: "./models/records/json.ts",
    API_SCHEMAS: "./models/schemas/api.ts",
    ANSWER_CHECKS: "./responses/answerChecks.ts",
    JSON_TESTS: "./responses/json.ts",
    ANSWERS: "./responses/answers.ts",
  }),
  /** The client's JSON types an answer may have without a schema of its own. */
  JSON_TYPES: Object.freeze(["JsonObject", "JsonValue"] as const),
  /** The opening and the closing of a placeholder in a path template. */
  PLACEHOLDER_OPEN: "{",
  PLACEHOLDER_CLOSE: "}",
  /** The indentation of one level. */
  INDENT: "  ",
} as const);

/**
 * Write the module of the endpoint methods.
 *
 * @param methods - The methods, sorted by name.
 * @returns The module's text, before formatting.
 *
 * @example
 * ```ts
 * const text = renderEndpointMethods(methods);
 * text.includes("async natal(body: NatalApiRequest, options?: CallOptions): Promise<NatalResponse>");   // true
 * ```
 */
export function renderEndpointMethods(
  methods: readonly SdkOperation[],
): string {
  const indent = METHOD_WRITER_CONFIG.INDENT;
  return [
    METHOD_WRITER_CONFIG.HEADER,
    imports(methods),
    [
      docBlock(METHOD_WRITER_CONFIG.CLASS_COMMENT, ""),
      "export abstract class EndpointMethods {",
      docBlock(METHOD_WRITER_CONFIG.REQUEST_COMMENT, indent),
      `${indent}abstract request(method: HttpMethod, path: string, options?: RequestOptions): Promise<JsonValue | string | Uint8Array>;`,
      ...methods.map((method) => `\n${methodText(method)}`),
      "}",
    ].join("\n"),
  ]
    .join("\n\n")
    .concat("\n");
}

/**
 * Write the module's imports.
 *
 * @param methods - The methods.
 * @returns The import lines, naming exactly what the methods use.
 */
function imports(methods: readonly SdkOperation[]): string {
  const config = METHOD_WRITER_CONFIG.IMPORTS;
  const schemaTypes = new Set<string>();
  const jsonTypes = new Set<string>(["JsonValue"]);
  const generatedChecks = new Set<string>();
  const jsonTests = new Set<string>();
  const readers = new Set<string>();
  for (const method of methods) {
    if (method.body !== undefined) {
      schemaTypes.add(method.body.typeName);
    }
    if (method.query !== undefined) {
      schemaTypes.add(method.query.typeName);
    }
    const answer = method.answer;
    if (answer.kind === "document") {
      readers.add("readDocument");
      continue;
    }
    readers.add("readJson");
    if (
      METHOD_WRITER_CONFIG.JSON_TYPES.some((type) => type === answer.typeName)
    ) {
      jsonTypes.add(answer.typeName);
    } else {
      schemaTypes.add(answer.typeName);
    }
    (answer.check.generated ? generatedChecks : jsonTests).add(
      answer.check.name,
    );
  }
  return [
    `import type { HttpMethod } from "${config.HTTP_METHOD}";`,
    `import type { CallOptions, RequestOptions } from "${config.CLIENT_RECORDS}";`,
    importLine(jsonTypes, config.JSON_RECORDS, true),
    importLine(schemaTypes, config.API_SCHEMAS, true),
    importLine(generatedChecks, config.ANSWER_CHECKS, false),
    importLine(jsonTests, config.JSON_TESTS, false),
    importLine(readers, config.ANSWERS, false),
  ]
    .filter((line) => line !== "")
    .join("\n");
}

/**
 * Write one import line.
 *
 * @param names - The names to import.
 * @param from - The module.
 * @param typesOnly - Whether the names are types, imported with `import type`.
 * @returns The line, or an empty text when there is nothing to import.
 */
function importLine(
  names: ReadonlySet<string>,
  from: string,
  typesOnly: boolean,
): string {
  if (names.size === 0) {
    return "";
  }
  const keyword = typesOnly ? "import type" : "import";
  return `${keyword} { ${[...names].sort().join(", ")} } from "${from}";`;
}

/**
 * Write one method with its comment.
 *
 * @param method - The method.
 * @returns The method's text, indented for the class body.
 */
function methodText(method: SdkOperation): string {
  const indent = METHOD_WRITER_CONFIG.INDENT;
  const inner = `${indent}${indent}`;
  const parameters = [
    ...method.pathArguments.map((argument) => `${argument.argument}: string`),
    ...(method.body === undefined
      ? []
      : [`body${method.body.required ? "" : "?"}: ${method.body.typeName}`]),
    ...(method.query === undefined
      ? []
      : [`query${method.query.required ? "" : "?"}: ${method.query.typeName}`]),
    "options?: CallOptions",
  ];
  const sent = [
    ...(method.body === undefined ? [] : ["json: body"]),
    ...(method.query === undefined ? [] : ["params: query"]),
    method.answer.kind === "document" ? "binary: true" : "enveloped: false",
    "signal: options?.signal",
  ];
  return [
    docBlock(methodComment(method), indent),
    `${indent}async ${method.methodName}(${parameters.join(", ")}): Promise<${resultType(method)}> {`,
    `${inner}const answer = await this.request(${JSON.stringify(method.verb)}, ${pathExpression(method)}, { ${sent.join(", ")} });`,
    `${inner}return ${readExpression(method)};`,
    `${indent}}`,
  ].join("\n");
}

/**
 * Write a method's comment.
 *
 * @param method - The method.
 * @returns The comment's lines.
 */
function methodComment(method: SdkOperation): readonly string[] {
  const summary = method.summary.endsWith(".")
    ? method.summary
    : `${method.summary}.`;
  const description =
    method.description === undefined
      ? []
      : ["", ...docLines(method.description)];
  return [
    ...docLines(summary),
    "",
    "@remarks",
    `Sends \`${method.verb} ${method.path}\`.`,
    ...description,
    "",
    ...method.pathArguments.map(
      (argument) =>
        `@param ${argument.argument} - ${
          argument.description === undefined
            ? `The ${argument.placeholder} segment of the path, escaped into it.`
            : docLines(argument.description).join(" ")
        }`,
    ),
    ...(method.body === undefined
      ? []
      : [
          `@param body - The request, as {@link ${method.body.typeName}} describes it.`,
        ]),
    ...(method.query === undefined
      ? []
      : [
          `@param query - The query, as {@link ${method.query.typeName}} describes it.`,
        ]),
    "@param options - The signal that cancels the call.",
    `@returns ${returnsText(method)}`,
    "@throws {@link AstroMansionError} or the subclass that names the cause, as {@link AstroMansion.request} describes. The code unexpected_answer means the answer did not have its published shape.",
  ];
}

/**
 * Write the type a method's promise resolves to.
 *
 * @param method - The method.
 * @returns The bytes of a document, the result inside a wrapper, or the answer's type.
 */
function resultType(method: SdkOperation): string {
  const answer = method.answer;
  if (answer.kind === "document") {
    return "Uint8Array";
  }
  return answer.opensEnvelope
    ? `${answer.typeName}["result"]`
    : answer.typeName;
}

/**
 * Write what a method's promise resolves to, for its comment.
 *
 * @param method - The method.
 * @returns The sentence.
 */
function returnsText(method: SdkOperation): string {
  const answer = method.answer;
  if (answer.kind === "document") {
    return `The document's bytes, sent as ${answer.mediaTypes.join(" or ")}.`;
  }
  const shape = METHOD_WRITER_CONFIG.JSON_TYPES.some(
    (type) => type === answer.typeName,
  )
    ? answer.typeName
    : `{@link ${answer.typeName}}`;
  return answer.opensEnvelope
    ? `The result inside the answer, after the answer was checked against ${shape}.`
    : `The answer, checked against ${shape}.`;
}

/**
 * Write the expression of a method's path.
 *
 * @param method - The method.
 * @returns A string literal for a fixed path, or a template that escapes each argument into its placeholder.
 */
function pathExpression(method: SdkOperation): string {
  if (method.pathArguments.length === 0) {
    return JSON.stringify(method.path);
  }
  let path = method.path;
  for (const argument of method.pathArguments) {
    path = path.replace(
      `${METHOD_WRITER_CONFIG.PLACEHOLDER_OPEN}${argument.placeholder}${METHOD_WRITER_CONFIG.PLACEHOLDER_CLOSE}`,
      `\${encodeURIComponent(${argument.argument})}`,
    );
  }
  return `\`${path}\``;
}

/**
 * Write how a method reads its answer.
 *
 * @param method - The method.
 * @returns The call that checks the answer, or that takes a document's bytes.
 */
function readExpression(method: SdkOperation): string {
  const answer = method.answer;
  const operation = JSON.stringify(method.methodName);
  if (answer.kind === "document") {
    return `readDocument(answer, ${operation})`;
  }
  const read = `readJson(answer, ${answer.check.name}, ${operation})`;
  return answer.opensEnvelope ? `${read}.result` : read;
}
